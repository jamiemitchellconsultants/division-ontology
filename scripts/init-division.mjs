#!/usr/bin/env node
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { runCli } from '../src/cli.mjs';
import { loadDivision, validateDivision } from '../src/division.mjs';
import { loadSources } from '../src/sources.mjs';

const usage = 'usage: node scripts/init-division.mjs --namespace https://.../ontology# --steward login [--steward login]...';

// Matches `narrative compile` output for zero fragments, so the copy passes `narrative check`.
const emptyNarrative = `<!-- GENERATED BY PROJECT NARRATIVE. Edit fragments, not this file. -->

# Project Narrative

This document records what was asked, what was decided, why, and what followed.

## Index

| # | Date | Title | Kind | Decision summary |
|---|---|---|---|---|


---

`;

export const templateHistory = ['docs/features/one-action-source-onboarding', 'docs/superpowers', 'docs/detailed-implementations'];

function parseArguments(argv) {
  const stewards = [];
  let namespace;
  for (let i = 0; i < argv.length; i++) {
    const value = argv[i + 1];
    if (value === undefined) throw new Error(usage);
    if (argv[i] === '--namespace' && namespace === undefined) namespace = value;
    else if (argv[i] === '--steward') stewards.push(value);
    else throw new Error(usage);
    i++;
  }
  if (namespace === undefined || stewards.length === 0) throw new Error(usage);
  return validateDivision({ namespace, stewards });
}

function rewriteCodeOwners(text, stewards) {
  const owners = stewards.map((login) => `@${login}`).join(' ');
  return text.split('\n').map((line) => {
    if (!line.trim() || line.trimStart().startsWith('#')) return line;
    return `${line.trim().split(/\s+/)[0]} ${owners}`;
  }).join('\n');
}

export async function initDivision(argv, options = {}) {
  const root = resolve(options.root ?? process.cwd());
  const division = parseArguments(argv);
  if (loadSources(join(root, 'sources.json')).length) throw new Error('init-division only runs on a fresh copy with no registered sources');
  const previous = loadDivision(root);

  const ontologyPath = join(root, 'core/ontology.ttl');
  writeFileSync(ontologyPath, readFileSync(ontologyPath, 'utf8').replaceAll(previous.namespace, division.namespace));
  writeFileSync(join(root, 'division.json'), `${JSON.stringify(division, null, 2)}\n`);

  const codeOwnersPath = join(root, '.github/CODEOWNERS');
  writeFileSync(codeOwnersPath, rewriteCodeOwners(readFileSync(codeOwnersPath, 'utf8'), division.stewards));

  const entries = join(root, 'narrative/entries');
  for (const name of readdirSync(entries)) if (name.endsWith('.md')) rmSync(join(entries, name));
  writeFileSync(join(entries, '.gitkeep'), '');
  writeFileSync(join(root, 'Narrative.md'), emptyNarrative);

  for (const path of templateHistory) if (existsSync(join(root, path))) rmSync(join(root, path), { recursive: true });

  await runCli(['build'], { root });
  return division;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const division = await initDivision(process.argv.slice(2));
  console.log(`Initialised division ontology for ${division.namespace} with stewards ${division.stewards.join(', ')}.`);
}
